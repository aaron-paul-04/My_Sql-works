SELECT  EMPLOYEE_ID, SALARY  FROM EMPLOYEES;
-- FETCH EMP WITH SALARY MORE THAN 5000
SELECT FIRST_NAME,LAST_NAME, SALARY
FROM EMPLOYEES 
WHERE SALARY>5000;
SELECT FIRST_NAME,LAST_NAME, SALARY
FROM EMPLOYEES 
WHERE SALARY BETWEEN 5000 AND 10000;
-- FETCH THE EMPLOYEES WORKING IN DEPARTMENT NUMBER 50 -- = ONLY USE FOR SINGLE VALUE
SELECT * FROM EMPLOYEES 
WHERE DEPARTMENT_ID=50;
-- FETCH THE EMPLOYEES WORKING IN DEPARTMENT NUMBER 50,60,70 = IN USES FOR MULTIPLE VALUE 
SELECT * FROM EMPLOYEES WHERE DEPARTMENT_ID IN (50,60,70);
-- FETCH EMP WHOSE NAME STARTS WITH A 
SELECT * FROM EMPLOYEES
WHERE FIRST_NAME LIKE 'A%'; -- % IS PLACEHOLDER(TYPE PER AFTER NAME), LIKE - PATTERN MATCH
-- FETCH EMP WHOSE NAME ENDS WITH A 
SELECT * FROM EMPLOYEES
WHERE FIRST_NAME LIKE '%A'; -- % IS PLACEHOLDER(TYPE PER BEFORE NAME), LIKE - PATTERN MATCH
SELECT * FROM EMPLOYEES
WHERE FIRST_NAME LIKE '%A%'; -- DISPLAYS ALL WHO MATCHS THE A
SELECT * FROM EMPLOYEES
WHERE DEPARTMENT_ID=50 AND SALARY>5000; -- "AND" BOTH THE QUERY NEED TO SATISFY 
SELECT * FROM EMPLOYEES
WHERE DEPARTMENT_ID=50 OR SALARY>5000; -- "OR" ANY ONE QUERY NEED TO SATISFY
-- DISPLAY THE EMPLOYEE WHO DOES NOT HAVE MANAGER
SELECT * FROM EMPLOYEES WHERE MANAGER_ID IS NULL;
-- FETCH THE EMP WHO HAD RECEIVED COMMISSION AND NOT RECEIVED
SELECT * FROM EMPLOYEES WHERE COMMISSION_PCT IS NULL; -- 1 NOT RECEIVED USES IS NULL
SELECT * FROM EMPLOYEES WHERE COMMISSION_PCT IS NOT NULL; -- 2 RECEIVED USES IS NOT NULL
