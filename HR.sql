/* 
DQL - DATA QUERY LANGUAGE
SIX IMPORTANT STATEMENTS
SELECT -- COLUMN INFORMATION TO FETCH FROM THE DB
FROM -- TABLE FROM WHICH WE NEED THE INFORMATION
WHERE -- CONDITION APPLIED TO FILTER THE INFOMATION -- WHERE AND -- SHOWS RANGE 
GROUP BY -- DATA SUMMARIZATION BY GROUPING THE DATA
HAVING -- CONDITION APPLIED AFTER GROUPING THE DATA
ORDER BY -- SORT THE DATA IN ASCENDING OR DESCENDING ORDER
LIMIT -- NUMBER OF ROWS WE NEED IN THE OUTPUT RESULT
OFFSET -- NUMBER OF ROWS WE NEED TO SKIP
*/
