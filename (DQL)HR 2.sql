-- FETCH DEPARTMENT WITH MORE THAN 4 EMPLOYEEES:
SELECT DEPARTMENT_ID, COUNT(*) AS EMP_COUNT
FROM EMPLOYEES
WHERE DEPARTMENT_ID IS NOT NULL
GROUP BY DEPARTMENT_ID
HAVING EMP_COUNT>4 -- HAVING 
ORDER BY EMP_COUNT ASC;
